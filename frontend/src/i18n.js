export const dictionaries = { en, es }

export function makeT(lang) {
  const dict = dictionaries[lang] || en
  return (key, vars) => {
    const v = dict[key] ?? en[key] ?? key
    // Un texto puede ser un string con {placeholders} o una función (para plurales
    // y otras variantes que un replace no cubre). Igual que el i18n del backend.
    if (typeof v === 'function') { try { return v(vars || {}) } catch { return key } }
    let s = v
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k])
    return s
  }
}